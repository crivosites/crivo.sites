/** Nomes de ícones, em ordem alfabética, para o seletor do painel. */
export const iconNames = Object.keys(iconRegistry).sort()

/** Devolve o ícone pelo nome; cai no fallback quando o nome não existe. */
export function getIcon(name: string | undefined, fallback: LucideIcon = Sparkles): LucideIcon {
  if (!name) return fallback
  return iconRegistry[name] ?? fallback
}
